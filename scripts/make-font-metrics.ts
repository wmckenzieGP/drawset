/** Writes src/markup/fontMetrics.ts: advance widths (per 1000 em) of the standard fonts for WinAnsi characters. */
import * as mupdf from "mupdf";
import { writeFileSync } from "node:fs";

const fonts = { Helvetica: "Helvetica", "Helvetica-Bold": "Helvetica-Bold", "Times-Roman": "Times-Roman", Courier: "Courier" };
const chars: number[] = [];
for (let c = 32; c < 127; c++) chars.push(c);
for (let c = 160; c < 256; c++) chars.push(c);
for (const c of [0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026, 0x20ac, 0xb2, 0xb3]) chars.push(c);
let out = "// Generated by scripts/make-font-metrics.ts — advance widths per 1000 units of em.\n";
out += "export const FONT_WIDTHS: Record<string, Record<number, number>> = {\n";
for (const [key, name] of Object.entries(fonts)) {
  const font = new mupdf.Font(name);
  const entries = [...new Set(chars)].map((c) => `${c}:${Math.round(font.advanceGlyph(font.encodeCharacter(c)) * 1000)}`);
  out += `  "${key}": {${entries.join(",")}},\n`;
}
out += "};\n";
writeFileSync("src/markup/fontMetrics.ts", out);
